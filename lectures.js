/* Список лекций. Это единственный файл, который надо править, когда
   добавляешь конспект.
 *
 * Как добавить лекцию — три шага:
 *
 *   1. Положить текст в папку lectures/ файлом с латинским именем,
 *      например lectures/statmodel-01.md
 *   2. Добавить сюда одну строку (запятая в конце обязательна).
 *   3. Закоммитить и запушить — через минуту появится на сайте.
 *
 * Поля строки:
 *   subject — предмет. Пиши ровно так, как он называется на главной:
 *             короткое название («Статмоделирование») или полное.
 *             Если не совпадёт — лекция уйдёт в полку «Разное».
 *   title   — название лекции, видно в списке.
 *   date    — дата пары, ДД.ММ.ГГГГ. Можно не указывать.
 *   file    — путь к файлу с текстом.
 *   pdf     — путь к PDF для скачивания. Можно не указывать: тогда кнопка
 *             «скачать» отдаёт сам file.
 *   main    — true у сводного конспекта курса. Такие записи стоят в списке
 *             первыми, остальные идут по датам.
 *   lectures — сколько лекций внутри сводного конспекта. По этому числу
 *             считается счётчик наверху: в одном файле лекций больше, чем
 *             строк в списке.
 *
 * Файл бывает трёх видов:
 *   .html — свёрстанная страница конспекта, открывается как есть. Белый лист,
 *           разбитый на страницы; рядом обычно лежит такой же .pdf.
 *   .pdf  — готовый конспект одним файлом: одинаково выглядит везде и
 *           нормально печатается. Можно поставить и в file, если страницы нет.
 *   .md   — текст конспекта, его показывает читалка lecture.html;
 *           образец оформления лежит в lectures/shablon.md.
 *
 * Пару .html + .pdf делает скрипт build_lecture.py из свёрстанного конспекта:
 *
 *   python build_lecture.py "путь/к/конспекту.html" lectures/имя.html
 */

